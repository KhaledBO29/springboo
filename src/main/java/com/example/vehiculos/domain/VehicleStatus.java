package com.example.vehiculos.domain;

/**
 * Enum que representa el estado de un vehículo
 */
public enum VehicleStatus {
    /**
     * Vehículo disponible para venta
     */
    AVAILABLE,
    
    /**
     * Vehículo vendido
     */
    SOLD,
    
    /**
     * Vehículo en mantenimiento
     */
    MAINTENANCE
}
